#!/usr/bin/env python3
"""Daily20 OOS cash-ledger portfolio research: no broker, leverage or LIVE writes.

Trades are *already out of sample*, generated by the existing fixed-parameter
annual expanding/purged signal research. This module never trains on realized
returns or ranks on future prices. Intraday drawdown is NOT observable from 1d.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from daily20 import load_bars, load_spec, market_file, write_json

START = pd.Timestamp("2024-01-01")
INITIAL_CASH = 100_000.0
SESSIONS_PER_YEAR = 252
STRATEGIES = ("LOGISTIC", "TREND_RULE")
VIX_LOW, VIX_HIGH = 20.0, 30.0


def prices_from_market(market, spec):
    result = {}
    for symbol in set(spec["core"]) | {"SPY", "QQQ", "^VIX"}:
        data = load_bars(market_file(market, symbol))[["open", "close"]].copy()
        if data.empty:
            raise RuntimeError(f"EMPTY_PRICE_{symbol}")
        if symbol != "^VIX" and (data.isna().any().any() or (data <= 0).any().any()):
            raise RuntimeError(f"INVALID_PORTFOLIO_MARK_PRICE_{symbol}")
        result[symbol] = data
    return result


def market_state(prices):
    spy = prices["SPY"]["close"]
    qqq = prices["QQQ"]["close"]
    vix = prices["^VIX"]["close"]
    # State is deliberately one complete US session behind signal date,
    # matching the existing training features, not today's price.
    slow_ma = spy.rolling(200, min_periods=200).mean()
    bull = spy.gt(slow_ma).where(slow_ma.notna()).shift(1)
    vix_prior = vix.shift(1)
    tech_lead = (qqq / spy).pct_change(20, fill_method=None).shift(1)
    result = pd.DataFrame(index=spy.index)
    result["bull"] = bull
    result["vix_prior"] = vix_prior
    result["tech_lead_prior20"] = tech_lead
    return result


def classify_state(row):
    bull = row["bull"]
    vix = row["vix_prior"]
    rel = row["tech_lead_prior20"]
    trend = "WARMUP" if pd.isna(bull) else "BULL" if bool(bull) else "BEAR"
    vol = "UNKNOWN" if pd.isna(vix) else "VIX_LT20" if vix < VIX_LOW else "VIX_20_30" if vix < VIX_HIGH else "VIX_GE30"
    leadership = "UNKNOWN" if pd.isna(rel) else "TECH_LEADS" if rel > 0 else "TECH_LAGS"
    return trend, vol, leadership


def prepared_events(all_trades, prices, state, *, strategy, excluded):
    required = {"symbol", "strategy", "signal_date", "entry_date", "exit_date",
                "gross_return", "net_return", "probability", "regime"}
    if not required.issubset(all_trades.columns):
        raise ValueError("OOS ledger missing columns: " + str(required - set(all_trades.columns)))
    records = all_trades[all_trades["strategy"] == strategy].copy()
    records = records[~records["symbol"].isin(excluded)]
    if records.empty:
        return []
    for key in ("signal_date", "entry_date", "exit_date"):
        records[key] = pd.to_datetime(records[key], errors="raise").dt.normalize()
    records = records[records["signal_date"] >= START]
    if records.duplicated(["symbol", "entry_date"]).any():
        raise ValueError("DUPLICATE_SYMBOL_SAME_OPEN")
    out = []
    for x in records.itertuples(index=False):
        symbol = str(x.symbol)
        if symbol not in prices:
            raise RuntimeError("UNRECOGNIZED_TRADE_SYMBOL:" + symbol)
        if not (x.signal_date < x.entry_date < x.exit_date):
            raise RuntimeError("INVALID_TRADING_EVENT_SEQUENCE")
        px = prices[symbol]
        if x.entry_date not in px.index or x.exit_date not in px.index:
            raise RuntimeError("MISSING_ENTRY_OR_EXIT_PRICE:" + symbol)
        market_open = float(px.at[x.entry_date, "open"])
        market_exit = float(px.at[x.exit_date, "close"])
        if not (np.isfinite(market_open) and np.isfinite(market_exit) and market_open > 0 and market_exit > 0):
            raise RuntimeError("INVALID_ENTRY_OR_EXIT_FILL_PRICE")
        # The completed test-year trade labels must refer to this exact adjusted price history.
        reconstructed = market_exit / market_open - 1.0
        if not np.isfinite(x.gross_return) or abs(float(x.gross_return) - reconstructed) > 2e-6:
            raise RuntimeError("STALE_OOS_TRADE_AGAINST_MARKET_DATA:" + symbol)
        if x.signal_date not in state.index:
            raise RuntimeError("NO_ASOF_MARKET_REGIME")
        row = state.loc[x.signal_date]
        trend, vol, leadership = classify_state(row)
        if trend != str(x.regime):
            raise RuntimeError("REGIME_INCONSISTENT_WITH_TRAINING_SIGNAL:" + symbol)
        # Same information available at the signal-date close: 20d momentum, NOT a future return.
        close = px["close"]
        mom20 = close.pct_change(20, fill_method=None).get(x.signal_date, np.nan)
        if strategy == "TREND_RULE":
            if not np.isfinite(mom20):
                raise RuntimeError("NO_ASOF_20D_MOMENTUM")
            priority = float(mom20)
        else:
            if not np.isfinite(x.probability):
                raise RuntimeError("MISSING_ASOF_LOGISTIC_SCORE")
            priority = float(x.probability)
        out.append({
            "symbol": symbol, "strategy": strategy,
            "signal_date": x.signal_date, "entry_date": x.entry_date,
            "exit_date": x.exit_date, "priority": priority,
            "signal_regime": trend, "signal_volatility": vol,
            "signal_tech_leadership": leadership,
            "market_open": market_open, "market_exit_close": market_exit,
        })
    return out


def validate_sessions(prices):
    sessions = prices["SPY"].index[prices["SPY"].index >= START]
    if sessions.empty or not sessions.is_monotonic_increasing or sessions.has_duplicates:
        raise RuntimeError("INVALID_SPY_EVALUATION_CALENDAR")
    if not sessions.isin(prices["QQQ"].index).all():
        raise RuntimeError("MISSING_QQQ_BENCHMARK_SESSION")
    return sessions


def simulate(events, prices, sessions, *,
             strategy, cohort, max_positions=5, allocation=0.2,
             round_trip_cost_bps=20.0, initial_cash=INITIAL_CASH):
    """Next-session open buys; all held positions exit after selected close.

    Entry/exit friction is applied symmetrically. Same-day *close* sale proceeds
    are never used to finance an *open* entry, and leverage is impossible.
    """
    if max_positions < 1 or not (0 < allocation <= 1) or round_trip_cost_bps < 0:
        raise ValueError("INVALID_PORTFOLIO_RISK_INPUTS")
    if max_positions * allocation > 1.0 + 1e-12:
        raise ValueError("MAX_GROSS_ALLOCATION_EXCEEDS_100_PERCENT")
    half_cost = round_trip_cost_bps / 20_000.0
    cash = float(initial_cash)
    holds = {}
    equity_rows = []
    executions = []
    skipped = {"max_positions": 0, "already_held": 0, "insufficient_cash": 0}
    entries = {}
    calendar = set(sessions)
    for row in events:
        if row["entry_date"] not in calendar or row["exit_date"] not in calendar:
            raise RuntimeError("TRADE_OUTSIDE_BACKTEST_SESSIONS")
        entries.setdefault(row["entry_date"], []).append(row)
    for dt in sessions:
        today = entries.get(dt, [])
        # Always use the current session open for existing positions' sizing marks.
        marked_at_open = cash
        for symbol, pos in holds.items():
            if dt not in prices[symbol].index:
                raise RuntimeError("MISSING_HELD_SYMBOL_OPEN:" + symbol)
            value = float(prices[symbol].at[dt, "open"])
            if not np.isfinite(value) or value <= 0:
                raise RuntimeError("INVALID_HELD_SYMBOL_OPEN:" + symbol)
            marked_at_open += pos["qty"] * value
        # Competing eligible entry signals are ranked on information known at
        # prior day's close (fixed model score or trailing momentum).
        for candidate in sorted(today, key=lambda x: (-x["priority"], x["symbol"])):
            symbol = candidate["symbol"]
            if symbol in holds:
                skipped["already_held"] += 1
                continue
            if len(holds) >= max_positions:
                skipped["max_positions"] += 1
                continue
            opening_price = float(prices[symbol].at[dt, "open"])
            execution_price = opening_price * (1 + half_cost)
            target_spend = marked_at_open * allocation
            actual_spend = min(target_spend, cash)
            if actual_spend <= initial_cash * 1e-8:
                skipped["insufficient_cash"] += 1
                continue
            qty = actual_spend / execution_price
            cash -= actual_spend
            holds[symbol] = {
                "qty": qty, "cost_basis": actual_spend, "entry_exec_price": execution_price,
                "entry_date": dt, "exit_date": candidate["exit_date"],
                "signal_date": candidate["signal_date"],
                "signal_regime": candidate["signal_regime"],
                "signal_volatility": candidate["signal_volatility"],
                "signal_tech_leadership": candidate["signal_tech_leadership"],
            }
        # Exit at close; sale proceeds cannot be spent at the same day's open.
        for symbol, pos in list(holds.items()):
            if pos["exit_date"] != dt:
                continue
            close_px = float(prices[symbol].at[dt, "close"])
            effective_sale = close_px * (1 - half_cost) * pos["qty"]
            cash += effective_sale
            pnl = effective_sale - pos["cost_basis"]
            executions.append({
                "strategy": strategy, "cohort": cohort, "symbol": symbol,
                "signal_date": pos["signal_date"].date().isoformat(),
                "entry_date": pos["entry_date"].date().isoformat(),
                "exit_date": dt.date().isoformat(), "entry_notional": pos["cost_basis"],
                "net_pnl": pnl, "realized_return": pnl / pos["cost_basis"],
                "signal_regime": pos["signal_regime"],
                "signal_volatility": pos["signal_volatility"],
                "signal_tech_leadership": pos["signal_tech_leadership"],
            })
            del holds[symbol]
        holdings_value = 0.0
        for symbol, pos in holds.items():
            if dt not in prices[symbol].index:
                raise RuntimeError("MISSING_HELD_SYMBOL_CLOSE:" + symbol)
            close_px = float(prices[symbol].at[dt, "close"])
            if not np.isfinite(close_px) or close_px <= 0:
                raise RuntimeError("INVALID_HELD_SYMBOL_CLOSE:" + symbol)
            holdings_value += pos["qty"] * close_px
        equity = cash + holdings_value
        if not np.isfinite(equity) or equity <= 0 or cash < -1e-6:
            raise RuntimeError("INVALID_CASH_EQUITY_STATE")
        equity_rows.append({
            "date": dt, "equity": equity, "cash": cash,
            "invested_market_value": holdings_value,
            "gross_exposure": holdings_value / equity,
            "active_positions": len(holds),
        })
    curve = pd.DataFrame(equity_rows).set_index("date")
    curve["daily_return"] = curve["equity"].pct_change(fill_method=None).fillna(
        curve["equity"].iloc[0] / initial_cash - 1
    )
    curve["drawdown"] = curve["equity"] / np.maximum.accumulate(
        np.maximum(curve["equity"], initial_cash)
    ) - 1
    return curve, pd.DataFrame(executions), skipped


def performance(curve, *, initial_cash=INITIAL_CASH):
    daily = curve["daily_return"].astype(float)
    end = float(curve["equity"].iloc[-1])
    vol = float(daily.std(ddof=1)) if len(daily) > 1 else 0.0
    annual_vol = vol * np.sqrt(SESSIONS_PER_YEAR)
    years = len(curve) / SESSIONS_PER_YEAR
    year_end = curve.groupby(curve.index.year)["equity"].last()
    prev = initial_cash
    calendar_returns = {}
    for year, ending in year_end.items():
        calendar_returns[str(year)] = float(ending / prev - 1)
        prev = float(ending)
    return {
        "total_return": end / initial_cash - 1.0,
        "cagr_252_sessions": float((end / initial_cash) ** (1 / years) - 1) if years else None,
        "max_close_drawdown": float(curve["drawdown"].min()),
        "ann_volatility_252": annual_vol,
        "sharpe_cash_zero": float(daily.mean() / vol * np.sqrt(SESSIONS_PER_YEAR)) if vol > 0 else None,
        "active_session_pct": float((curve["active_positions"] > 0).mean()),
        "average_gross_exposure": float(curve["gross_exposure"].mean()),
        "ending_equity": end,
        "session_count": int(len(curve)),
        "calendar_year_returns": calendar_returns,
    }


def buy_hold(prices, sessions, symbol, *, initial_cash=INITIAL_CASH):
    x = prices[symbol]["close"].reindex(sessions)
    if x.isna().any() or (x <= 0).any():
        raise RuntimeError("INVALID_BUY_HOLD_BENCHMARK_HISTORY")
    # Baseline first *close*, no intraday entry edge, adjusted price basis.
    eq = initial_cash * x / x.iloc[0]
    curve = pd.DataFrame({"equity": eq})
    curve["active_positions"] = 1
    curve["gross_exposure"] = 1.0
    curve["daily_return"] = curve["equity"].pct_change(fill_method=None).fillna(0.0)
    curve["drawdown"] = curve["equity"] / curve["equity"].cummax() - 1
    return performance(curve, initial_cash=initial_cash)


def conditional_daily_stats(curve, state):
    joined = curve[["daily_return"]].join(state, how="left")
    tags = joined.apply(classify_state, axis=1, result_type="expand")
    tags.columns = ["market_regime_lagged", "vix_bucket_lagged", "technology_leadership_lagged"]
    joined = joined.join(tags)
    result = {}
    for key in tags.columns:
        result[key] = {}
        for name, part in joined.groupby(key, dropna=False):
            result[key][str(name)] = {
                "sessions": len(part),
                "average_portfolio_daily_return": float(part["daily_return"].mean()),
            }
    return result


def trade_group_stats(executions):
    out = {}
    for field in ("signal_regime", "signal_volatility", "signal_tech_leadership"):
        out[field] = {}
        if executions.empty:
            continue
        for key, g in executions.groupby(field):
            r = g["realized_return"]
            out[field][str(key)] = {
                "trades": int(len(g)),
                "mean_net_trade_return": float(r.mean()),
                "median_net_trade_return": float(r.median()),
                "win_rate": float((r > 0).mean()),
                "realized_net_pnl": float(g["net_pnl"].sum()),
            }
    return out


def build_report(spec, market, trade_csv, out):
    output = Path(out)
    output.mkdir(parents=True, exist_ok=True)
    prices = prices_from_market(market, spec)
    sessions = validate_sessions(prices)
    context = market_state(prices)
    trades = pd.read_csv(trade_csv)
    all_reports, all_equity, all_fills, annual = [], [], [], []
    by_regime = {}
    high_risk = set(spec["high_risk_shadow_only"])
    benchmarks = {symbol: buy_hold(prices, sessions, symbol) for symbol in ("SPY", "QQQ")}

    for strategy in STRATEGIES:
        for cohort in ("ALL_20", "EXCLUDE_HIGH_RISK"):
            excluded = set() if cohort == "ALL_20" else high_risk
            events = prepared_events(trades, prices, context, strategy=strategy, excluded=excluded)
            for capacity in (3, 5):
                for cost_bps in (float(spec["round_trip_cost_bps"]), 40.0):
                    curve, executed, skipped = simulate(
                        events, prices, sessions, strategy=strategy, cohort=cohort,
                        max_positions=capacity, allocation=1.0 / capacity,
                        round_trip_cost_bps=cost_bps,
                    )
                    scenario = f"{strategy}__{cohort}__POS{capacity}__COST{int(cost_bps)}BP"
                    metrics = performance(curve)
                    metrics.update({
                        "scenario": scenario, "strategy": strategy, "cohort": cohort,
                        "max_positions": capacity, "target_allocation": 1.0 / capacity,
                        "round_trip_cost_bps": cost_bps,
                        "candidate_trades": len(events),
                        "executed_trades": len(executed),
                        "dropped_candidates": skipped,
                        "is_primary": capacity == 5 and cost_bps == float(spec["round_trip_cost_bps"]),
                        "research_only": True,
                        "not_live": True,
                    })
                    all_reports.append(metrics)
                    for date, row in curve.iterrows():
                        all_equity.append({
                            "scenario": scenario, "date": date.date().isoformat(),
                            "equity": float(row["equity"]),
                            "daily_return": float(row["daily_return"]),
                            "drawdown": float(row["drawdown"]),
                            "active_positions": int(row["active_positions"]),
                            "gross_exposure": float(row["gross_exposure"]),
                            "cash": float(row["cash"]),
                        })
                    if not executed.empty:
                        for x in executed.to_dict("records"):
                            all_fills.append({"scenario": scenario, **x})
                    for year, value in metrics["calendar_year_returns"].items():
                        annual.append({"scenario": scenario, "year": year, "net_return": value})
                    if metrics["is_primary"]:
                        by_regime[scenario] = {
                            "trades_at_entry": trade_group_stats(executed),
                            "portfolio_daily_conditioned_on_lagged_state":
                                conditional_daily_stats(curve, context),
                        }

    pd.DataFrame(all_reports).drop(columns=["calendar_year_returns", "dropped_candidates"]).to_csv(
        output / "portfolio_scenarios.csv", index=False)
    pd.DataFrame(all_equity).to_csv(output / "portfolio_daily_equity.csv", index=False)
    pd.DataFrame(all_fills).to_csv(output / "portfolio_executions.csv", index=False)
    pd.DataFrame(annual).to_csv(output / "portfolio_annual.csv", index=False)
    summary = {
        "status": "RESEARCH_ONLY",
        "research_only": True, "live_execution": False, "portfolio_mdd_available": True,
        "oos_start": str(sessions[0].date()), "oos_end": str(sessions[-1].date()),
        "benchmark": benchmarks, "scenario_count": len(all_reports),
        "selected_model": None, "tradable_strategy_approved": False,
        "primary_scenarios": [x for x in all_reports if x["is_primary"]],
        "scenario_results": all_reports, "regime_attribution": by_regime,
        "warnings": [
            "Fixed 2026-selected universe creates historical selection/survivorship bias",
            "Signal candidate rows are completed retrospective OOS trades, not live fills",
            "Every candidate was produced under SPY > lagged SMA200 and VIX <=35: no BEAR entries tested",
            "Market EOD close-only drawdown misses intraday drawdown and opening-gap stop risk",
            "Yahoo adjusted historical prices are revised; fill/cost assumptions are simulated",
            "SPY/QQQ benchmark assumes first-session close buy and zero brokerage costs",
            "Cash earns 0% and fractional shares are allowed; portfolio is long-only, no leverage",
            "Capacity changes position weight (1/N); this is not a pure max-position sensitivity",
            "Stress variants are diagnostics, not hyperparameter selection on the test sample",
        ],
    }
    write_json(output / "portfolio_summary.json", summary)
    if len(all_reports) != 16 or len(all_equity) != len(sessions) * 16:
        raise RuntimeError("INCOMPLETE_PORTFOLIO_SCENARIOS")
    if not any(x["executed_trades"] > 0 for x in all_reports):
        raise RuntimeError("ALL_PORTFOLIO_TRADES_EMPTY")
    print(json.dumps({
        "DAILY20_PORTFOLIO": "COMPLETE",
        "scenarios": len(all_reports),
        "sessions": len(sessions),
        "primary": [{"scenario": x["scenario"],
                     "total_return": round(x["total_return"], 5),
                     "max_close_drawdown": round(x["max_close_drawdown"], 5),
                     "executed_trades": x["executed_trades"]}
                    for x in summary["primary_scenarios"]],
        "sp500_total_return": round(benchmarks["SPY"]["total_return"], 5),
    }))
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="research/kalman_daily20/universe.json")
    parser.add_argument("--market", required=True)
    parser.add_argument("--trades", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    build_report(load_spec(args.config), args.market, args.trades, args.out)


if __name__ == "__main__":
    main()
