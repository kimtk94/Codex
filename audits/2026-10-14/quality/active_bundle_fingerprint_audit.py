"""Match active Vercel uploaded SOURCE file digests to offline-built releases.

Read-only provenance comparison:
- Vercel GET-only source file UID is SHA-1 of file bytes for the independently
  retrieved, complete active main vercel.json.
- No Vercel API calls, tokens, server access, deployment or alias changes.
- A source file match does NOT guarantee runtime Lambda or API responses.
- Main baseline is a separate read-only checkout; this module never executes
  or builds it. It compares manifests generated by a separate CI step.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from hub_offline_release_gate import decode_manifest

HERE=Path(__file__).resolve()
PROJECT_ROOT=HERE.parents[3]
BASELINE_SNAPSHOT=PROJECT_ROOT/"audits/2026-10-15/vercel_active_file_digests.json"
MAIN_HOST="kalman-investment-hub-v2.vercel.app"
KEY_FILES=("app.js","api/assets.js","api/health.js","index.html","vercel.json")


def _manifest(root:Path,version:str):
    location=root/"kalman-hub-recovery"/version/"source_manifest.ndjson"
    if not location.is_file():
        return None
    return decode_manifest(location.read_text(encoding="utf-8"))


def digest_report(live:dict, files:dict):
    """Report exact source byte identity; not deployed runtime verification."""
    matches={}
    local={}
    for name in KEY_FILES:
        local[name]=hashlib.sha1(files[name]).hexdigest()
        matches[name]=local[name] == live.get(name)
    return {"matched_files":[k for k in KEY_FILES if matches[k]],
            "unmatched_files":[k for k in KEY_FILES if not matches[k]],
            "sha1":local,
            "source_fingerprint_match":all(matches.values()),
            "app_and_api_identical":matches["app.js"] and matches["api/assets.js"]}


def legacy_exposure_flags(files:dict):
    """Static code signals only; may not represent the served runtime bundle."""
    app=files["app.js"].decode("utf-8")
    api=files["api/assets.js"].decode("utf-8")
    return {
      "legacy_direct_net_renderer":"var gross=n(x.realized_return_pct),net=n(x.net_return)" in app,
      "guarded_net_renderer":"function verifiedNet(x)" in app and "net=verifiedNet(x)" in app,
      "legacy_raw_net_api_projection":"realized_return_pct,net_return,round_trip_cost_bps" in api,
      "guarded_net_api_projection":"NULL::numeric AS net_return" in api and "NULL::numeric AS round_trip_cost_bps" in api,
    }


def audit(baseline_root:Path, candidate_root:Path, snapshot:dict):
    if not isinstance(snapshot,dict) or not isinstance(snapshot.get("hosts"),dict):
        raise ValueError("INVALID_VERCEL_DIGEST_SNAPSHOT")
    host=snapshot["hosts"].get(MAIN_HOST)
    if not isinstance(host,dict) or not isinstance(host.get("files"),dict):
        raise ValueError("MAIN_ALIAS_DIGEST_MISSING")
    live=host["files"]
    for name in KEY_FILES:
        dig=live.get(name)
        if not isinstance(dig,str) or len(dig)!=40 or any(c not in "0123456789abcdef" for c in dig):
            raise ValueError("BAD_VERCEL_FILE_UID")
    baseline=[]
    for minor in range(23,37):
        ver=f"v7.4.{minor}"
        files=_manifest(baseline_root,ver)
        if files is None:
            continue
        scan=digest_report(live,files)
        baseline.append({
          "release":ver,
          "matched_files":scan["matched_files"],
          "app_and_api_identical":scan["app_and_api_identical"],
          "static_source_flags":legacy_exposure_flags(files),
        })
    candidate=_manifest(candidate_root,"v7.4.36")
    if candidate is None:
        raise ValueError("BUILT_AUDIT_CANDIDATE_MISSING")
    candidate_scan=digest_report(live,candidate)
    best=sorted(baseline,key=lambda x:len(x["matched_files"]),reverse=True)[:3]
    return {
      "verdict":"SOURCE_FINGERPRINT_AUDIT_COMPLETE_RELEASE_HOLD",
      "observed_active_alias_deployment":host["deployment"],
      "comparison_rule":"sha1(source bytes) equals Vercel file UID; not runtime attestation",
      "baseline_count":len(baseline),
      "baseline_top_matches":best,
      "baseline_app_api_exact_versions":[x["release"] for x in baseline if x["app_and_api_identical"]],
      "audit_candidate_app_api_exact_active":candidate_scan["app_and_api_identical"],
      "candidate_matched_files":candidate_scan["matched_files"],
      "candidate_source_sha1":candidate_scan["sha1"],
      "candidate_source_guards":legacy_exposure_flags(candidate),
      "runtime_http_attested":False,
      "release_authorized":False,
    }


def main():
    cli=argparse.ArgumentParser()
    cli.add_argument("--baseline-root",required=True)
    cli.add_argument("--output",default="")
    args=cli.parse_args()
    base=Path(args.baseline_root).resolve()
    expected=(PROJECT_ROOT/"baseline_main").resolve()
    if base!=expected:
        raise SystemExit("REFUSED_BASELINE_ROOT_OUTSIDE_READONLY_CI_CHECKOUT")
    snap=json.loads(BASELINE_SNAPSHOT.read_text(encoding="utf-8"))
    report=audit(base,PROJECT_ROOT,snap)
    if args.output:
        dest=Path(args.output)
        dest.write_text(json.dumps(report,indent=2,sort_keys=True)+"\n",encoding="utf-8")
    print(json.dumps({k:v for k,v in report.items() if k!="candidate_source_sha1"},ensure_ascii=False,sort_keys=True))


if __name__=="__main__":
    main()
